"""Generates docs/pt-BR/user-guide.md (Portuguese) and docs/en/user-guide.md (English) from vulcan_celox/web/help/conteudo*.json.

Usage: python3 scripts/manual_md.py                generates both
     python3 scripts/manual_md.py saida.md       Portuguese only, into saida.md
     python3 scripts/manual_md.py saida.md --en  English only, into saida.md
The app's Help content and the Markdown manual come from the same file; validate.sh compares the two.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HELP = ROOT / "vulcan_celox" / "web" / "help"
LANGS = {
    "pt": {
        "src": HELP / "conteudo.json", "out": ROOT / "docs" / "pt-BR" / "user-guide.md", "img": "../../vulcan_celox/web/img/manual",
        "title": "Manual do Vulcan Celox",
        "note": "> Gerado por `scripts/manual_md.py` a partir de `vulcan_celox/web/help/conteudo.json`, o mesmo conteúdo da tela Ajuda do app (⌘?). Não edite este arquivo à mão.",
        "toc": "Sumário", "faq": "Perguntas frequentes", "faq_id": "perguntas-frequentes",
        "head": "| Atalho | Faz |\n|--------|-----|\n",
    },
    "en": {
        "src": HELP / "conteudo.en.json", "out": ROOT / "docs" / "en" / "user-guide.md", "img": "../../vulcan_celox/web/img/manual",
        "title": "Vulcan Celox manual",
        "note": "> Generated by `scripts/manual_md.py` from `vulcan_celox/web/help/conteudo.en.json`, the same content as the app's Help screen (⌘?). Do not edit this file by hand.",
        "toc": "Contents", "faq": "Frequently asked questions", "faq_id": "frequently-asked-questions",
        "head": "| Shortcut | Action |\n|----------|--------|\n",
    },
}


def block(b, cfg):
    IMG = cfg["img"]
    if "p" in b:
        return b["p"]
    if "ul" in b:
        return "\n".join(f"- {t}" for t in b["ul"])
    if "passos" in b:
        return "\n".join(f"{i}. {t}" for i, t in enumerate(b["passos"], 1))
    if "img" in b:
        return f"![{b.get('alt', '')}]({IMG}/{b['img']})"
    if "atalhos" in b:
        rows = "\n".join(f"| `{k}` | {d} |" for k, d in b["atalhos"])
        return cfg["head"] + rows
    return ""


def render(data, lang="pt"):
    cfg = LANGS[lang]
    out = [f"# {cfg['title']}", "", cfg["note"], "", f"## {cfg['toc']}", ""]
    out += [f"- [{s['titulo']}](#{s['id']}): {s['resumo']}" for s in data["secoes"]]
    out += [f"- [{cfg['faq']}](#{cfg['faq_id']})", ""]
    for s in data["secoes"]:
        out += [f'<a id="{s["id"]}"></a>', "", f"## {s['titulo']}", "", f"*{s['resumo']}*", ""]
        for b in s["blocos"]:
            out += [block(b, cfg), ""]
    out += [f'<a id="{cfg["faq_id"]}"></a>', "", f"## {cfg['faq']}", ""]
    for f in data["faq"]:
        out += [f"**{f['q']}**", "", f["a"], ""]
    return "\n".join(out).rstrip() + "\n"


def write(lang, target):
    cfg = LANGS[lang]
    target.write_text(render(json.loads(cfg["src"].read_text(encoding="utf-8")), lang), encoding="utf-8")
    print(target)


def main():
    args = [a for a in sys.argv[1:] if a != "--en"]
    lang = "en" if "--en" in sys.argv[1:] else "pt"
    if args:
        write(lang, Path(args[0]))
    elif "--en" in sys.argv[1:]:
        write("en", LANGS["en"]["out"])
    else:
        for code in ("pt", "en"):
            write(code, LANGS[code]["out"])


if __name__ == "__main__":
    main()
